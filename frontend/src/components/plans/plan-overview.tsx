import { ShieldCheck, ShieldX, Sparkles, CheckCircle2 } from "lucide-react";
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { TaskPlanRead } from "@/types/backend";
import { formatDate } from "@/lib/formatters";

interface PlanOverviewProps {
  plan: TaskPlanRead;
}

export function PlanOverview({ plan }: PlanOverviewProps) {
  const { plan_json: planJson, policy_result: policy, model, created_at: createdAt, approval_status: approvalStatus } = plan;

  return (
    <Card className="bg-[#111820] border-white/8 shadow-sm">
      <CardHeader className="pb-3 border-b border-white/[0.06]">
        <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-2">
          <div>
            <CardTitle className="text-base font-semibold text-white flex items-center gap-2">
              <Sparkles className="h-4 w-4 text-[#55D6C2]" />
              AI Execution Plan Specification
            </CardTitle>
            <CardDescription className="text-xs text-zinc-400">
              Generated by {model} on {formatDate(createdAt)}
            </CardDescription>
          </div>

          <div className="flex items-center gap-2 shrink-0">
            <Badge
              variant={policy.allowed ? "success" : "destructive"}
              className="text-xs font-mono"
            >
              {policy.allowed ? (
                <>
                  <ShieldCheck className="h-3 w-3 mr-1 text-emerald-400" />
                  Policy Allowed
                </>
              ) : (
                <>
                  <ShieldX className="h-3 w-3 mr-1 text-rose-400" />
                  Policy Blocked
                </>
              )}
            </Badge>

            <Badge variant="outline" className="text-xs font-mono uppercase">
              Status: {approvalStatus}
            </Badge>
          </div>
        </div>
      </CardHeader>

      <CardContent className="pt-4 space-y-4 text-xs">
        {/* Title & Summary */}
        <div className="space-y-1">
          <span className="text-[10px] font-mono uppercase tracking-wider text-zinc-400 font-semibold block">
            Plan Title
          </span>
          <p className="text-sm font-semibold text-zinc-100">{planJson.title}</p>
        </div>

        <div className="space-y-1">
          <span className="text-[10px] font-mono uppercase tracking-wider text-zinc-400 font-semibold block">
            Objective Summary
          </span>
          <p className="text-xs text-zinc-300 leading-relaxed bg-[#0B0E12] p-3 rounded-md border border-white/6">
            {planJson.summary}
          </p>
        </div>

        {/* Reasoning Summary */}
        {planJson.reasoning_summary && (
          <div className="space-y-1">
            <span className="text-[10px] font-mono uppercase tracking-wider text-zinc-400 font-semibold block">
              Architectural Reasoning
            </span>
            <p className="text-xs text-zinc-400 leading-relaxed bg-[#0B0E12]/80 p-3 rounded-md border border-white/6">
              {planJson.reasoning_summary}
            </p>
          </div>
        )}

        {/* Success Criteria */}
        {planJson.success_criteria && planJson.success_criteria.length > 0 && (
          <div className="space-y-1.5 pt-1">
            <span className="text-[10px] font-mono uppercase tracking-wider text-zinc-400 font-semibold block">
              Measurable Success Criteria
            </span>
            <ul className="space-y-1">
              {planJson.success_criteria.map((crit, idx) => (
                <li key={idx} className="flex items-start gap-2 text-zinc-300">
                  <CheckCircle2 className="h-3.5 w-3.5 text-[#55D6C2] shrink-0 mt-0.5" />
                  <span>{crit}</span>
                </li>
              ))}
            </ul>
          </div>
        )}
      </CardContent>
    </Card>
  );
}
